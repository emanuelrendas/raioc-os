#!/usr/bin/env node
/**
 * RAIOC OS - Site Pages Sync Tool (MISSION-004, Decision B)
 * Reads all canonical authoring .html files from disk and regenerates
 * src/site/site-pages.js — the canonical production source of truth.
 *
 * MANDATORY: Run this before every deploy after editing any .html file.
 *   node tools/sync-site-pages.mjs
 *
 * Exit codes:
 *   0 — Success: all required pages synced
 *   1 — Failure: one or more required pages missing from disk
 *
 * Owner: Emanuel Rendas (Principal Advisor)
 * Risk Tier: Tier 1 — Client-Facing Public Identity & Intake
 * Audit Trail: Git commit history + checksum log below
 */

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');

// Required pages — all must be present on disk or sync will abort with exit 1
const REQUIRED_PAGES = [
  'index',
  'about',
  'advisory',
  'contact',
  'instruments',
  'intelligence',
  'addresses',
];

// Optional pages — synced if present, silently skipped if absent
const OPTIONAL_PAGES = [
  'dashboard',
  'mission-control',
];

const OUTPUT_FILE = path.join(ROOT, 'src', 'site', 'site-pages.js');

function sha256(content) {
  return crypto.createHash('sha256').update(content, 'utf8').digest('hex').slice(0, 16);
}

function readHtmlFile(pageName) {
  const candidates = [
    path.join(ROOT, `${pageName}.html`),
    path.join(ROOT, 'public', `${pageName}.html`),
  ];
  for (const candidate of candidates) {
    if (fs.existsSync(candidate)) {
      return { content: fs.readFileSync(candidate, 'utf8'), path: candidate };
    }
  }
  return null;
}

console.log('\n╔══════════════════════════════════════════════════════╗');
console.log('║  RAIOC OS — site-pages.js Sync (Decision B)         ║');
console.log('║  Canonical production bundle regeneration            ║');
console.log('╚══════════════════════════════════════════════════════╝\n');

const pages = {};
const missing = [];

// Process required pages — abort on any missing
for (const name of REQUIRED_PAGES) {
  const result = readHtmlFile(name);
  if (result === null) {
    missing.push(name);
    console.error(`[MISSING] REQUIRED page not found on disk: ${name}.html`);
  } else {
    pages[name] = result.content;
    console.log(`[OK]      ${name}.html  (${result.content.length} bytes, sha256: ${sha256(result.content)})`);
  }
}

if (missing.length > 0) {
  console.error(`\n[ABORT] ${missing.length} required page(s) missing: ${missing.join(', ')}`);
  console.error('[ABORT] site-pages.js was NOT updated. Fix missing files and re-run.\n');
  process.exit(1);
}

// Process optional pages — skip silently if absent
for (const name of OPTIONAL_PAGES) {
  const result = readHtmlFile(name);
  if (result === null) {
    console.log(`[SKIP]    ${name}.html  (optional — not found on disk)`);
  } else {
    pages[name] = result.content;
    console.log(`[OK]      ${name}.html  (${result.content.length} bytes, sha256: ${sha256(result.content)})`);
  }
}

// Write output
const now = new Date().toISOString();
const entries = Object.entries(pages)
  .map(([key, html]) => `  ${JSON.stringify(key)}: ${JSON.stringify(html)}`)
  .join(',\n');

const output = `/**
 * CANONICAL PRODUCTION SOURCE OF TRUTH — RAIOC OS Frontend
 * Decision B (locked 2026-08-28): This file is the single authoritative source for all served HTML pages.
 * Root .html files (index.html, about.html, ...) are AUTHORING-ONLY and are NOT served directly.
 *
 * TO UPDATE A PAGE:
 *   1. Edit the corresponding root .html file (e.g. about.html)
 *   2. Run: node tools/sync-site-pages.mjs
 *   3. Commit BOTH the .html file and this file together
 *   4. Deploy
 *
 * AUTO-GENERATED by tools/sync-site-pages.mjs — DO NOT EDIT MANUALLY
 * Generated: ${now}
 */

export const sitePages = {
${entries}
};
`;

fs.writeFileSync(OUTPUT_FILE, output, 'utf8');

const outputSize = fs.statSync(OUTPUT_FILE).size;
const outputHash = sha256(output);

console.log(`\n[WRITTEN] ${OUTPUT_FILE}`);
console.log(`[SIZE]    ${(outputSize / 1024).toFixed(1)} KB`);
console.log(`[HASH]    ${outputHash}`);
console.log(`[PAGES]   ${Object.keys(pages).length} pages synced: ${Object.keys(pages).join(', ')}`);

console.log('\n╔══════════════════════════════════════════════════════╗');
console.log('║  [DEPLOY GATE]                                       ║');
console.log('║  Commit src/site/site-pages.js before deploying.    ║');
console.log('║  git add src/site/site-pages.js && git commit       ║');
console.log('╚══════════════════════════════════════════════════════╝\n');
