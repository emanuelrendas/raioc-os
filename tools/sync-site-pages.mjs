#!/usr/bin/env node
/**
 * RAIOC OS - Site Pages Sync Tool (MISSION-004)
 * Reads all canonical HTML files from disk and regenerates src/site/site-pages.js
 * so that the bundled fallback is byte-for-byte identical to live disk files.
 *
 * Usage: node tools/sync-site-pages.mjs
 *
 * Owner: Emanuel Rendas (Principal Advisor)
 * Risk Tier: Tier 1 — Client-Facing Public Identity & Intake
 * Audit Trail: Git commit history
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');

const PAGE_NAMES = [
  'index',
  'about',
  'advisory',
  'contact',
  'instruments',
  'intelligence',
  'addresses',
  'dashboard',
  'mission-control',
];

const OUTPUT_FILE = path.join(ROOT, 'src', 'site', 'site-pages.js');

function readHtmlFile(pageName) {
  const candidates = [
    path.join(ROOT, `${pageName}.html`),
    path.join(ROOT, 'public', `${pageName}.html`),
  ];
  for (const candidate of candidates) {
    if (fs.existsSync(candidate)) {
      return fs.readFileSync(candidate, 'utf8');
    }
  }
  return null;
}

const pages = {};
const missing = [];

for (const name of PAGE_NAMES) {
  const html = readHtmlFile(name);
  if (html === null) {
    missing.push(name);
    console.warn(`[sync-site-pages] WARNING: ${name}.html not found on disk — skipping.`);
  } else {
    pages[name] = html;
    console.log(`[sync-site-pages] Loaded ${name}.html (${html.length} bytes)`);
  }
}

if (missing.length > 0) {
  console.warn(`[sync-site-pages] ${missing.length} page(s) missing from disk: ${missing.join(', ')}`);
}

const entries = Object.entries(pages)
  .map(([key, html]) => `  ${JSON.stringify(key)}: ${JSON.stringify(html)}`)
  .join(',\n');

const output = `/**
 * Bundled Static Site Pages for Zero-I/O Serverless Serving
 * AUTO-GENERATED by tools/sync-site-pages.mjs — DO NOT EDIT MANUALLY
 * Run: node tools/sync-site-pages.mjs
 * Generated: ${new Date().toISOString()}
 * Source of Truth: Disk HTML files (index.html, about.html, ...)
 */

export const sitePages = {
${entries}
};
`;

fs.writeFileSync(OUTPUT_FILE, output, 'utf8');
console.log(`\n[sync-site-pages] ✅ Written ${Object.keys(pages).length} pages to ${OUTPUT_FILE}`);
console.log(`[sync-site-pages] File size: ${(fs.statSync(OUTPUT_FILE).size / 1024).toFixed(1)} KB`);
